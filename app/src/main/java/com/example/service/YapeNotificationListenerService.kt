package com.example.service

import android.app.Notification
import android.content.ComponentName
import android.content.Context
import android.os.Build
import android.provider.Settings
import android.service.notification.NotificationListenerService
import android.service.notification.StatusBarNotification
import android.text.TextUtils
import android.util.Log
import com.example.YapeMonitorApp
import com.example.data.model.YapePayment
import com.example.parser.YapeNotificationParser
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.launch
import java.util.Locale
import java.util.concurrent.ConcurrentHashMap

class YapeNotificationListenerService : NotificationListenerService() {

    private val scope = CoroutineScope(Dispatchers.IO)

    companion object {
        private const val TAG = "YapeListenerService"

        // Active singleton instance when bound by Android system
        @Volatile
        var instance: YapeNotificationListenerService? = null
            private set

        private val _isListenerConnected = MutableStateFlow(false)
        val isListenerConnected: StateFlow<Boolean> = _isListenerConnected.asStateFlow()

        // Cache of recently processed payment fingerprints to prevent duplicate triggers
        private val processedPayments = ConcurrentHashMap<String, Long>()
        private const val DEDUPLICATION_WINDOW_MS = 15000L

        /**
         * Registers a payment fingerprint to prevent immediate duplicates from simulations or updates.
         */
        fun markAsProcessed(sender: String, amount: Double) {
            val fingerprint = "${sender.trim().lowercase()}_${String.format(Locale.US, "%.2f", amount)}"
            processedPayments[fingerprint] = System.currentTimeMillis()
        }

        /**
         * Checks if the user has granted notification listener permission to this app.
         */
        fun isNotificationAccessGranted(context: Context): Boolean {
            val packageName = context.packageName
            val flat = Settings.Secure.getString(
                context.contentResolver,
                "enabled_notification_listeners"
            ) ?: return false

            val names = flat.split(":")
            for (name in names) {
                val cn = ComponentName.unflattenFromString(name)
                if (cn != null && TextUtils.equals(packageName, cn.packageName)) {
                    return true
                }
            }
            return false
        }
    }

    override fun onListenerConnected() {
        super.onListenerConnected()
        instance = this
        _isListenerConnected.value = true
        Log.d(TAG, "NotificationListenerService connected and monitoring.")

        // Automatically scan notifications that are already sitting in the status bar!
        scanActiveNotifications()
    }

    override fun onListenerDisconnected() {
        super.onListenerDisconnected()
        if (instance == this) {
            instance = null
        }
        _isListenerConnected.value = false
        Log.d(TAG, "NotificationListenerService disconnected.")
    }

    override fun onNotificationPosted(sbn: StatusBarNotification?) {
        super.onNotificationPosted(sbn)
        if (sbn == null) return
        handleNotification(sbn, isCatchUp = false)
    }

    /**
     * Scans all notifications currently in the status bar to catch any existing/historical Yape payments.
     */
    fun scanActiveNotifications(): Int {
        var count = 0
        try {
            val activeList = getActiveNotifications()
            if (activeList != null && activeList.isNotEmpty()) {
                Log.d(TAG, "Scanning ${activeList.size} active notifications in status bar...")
                for (sbn in activeList) {
                    if (handleNotification(sbn, isCatchUp = true)) {
                        count++
                    }
                }
            } else {
                Log.d(TAG, "No active notifications returned by system")
            }
        } catch (e: Exception) {
            Log.e(TAG, "Error scanning active notifications", e)
        }
        return count
    }

    /**
     * Inspects a single notification, parses it with YapeNotificationParser, and inserts if valid and not already stored.
     */
    private fun handleNotification(sbn: StatusBarNotification, isCatchUp: Boolean): Boolean {
        val packageName = sbn.packageName ?: ""

        // NEVER process notifications generated by OUR OWN app
        if (packageName == applicationContext.packageName) {
            return false
        }

        val notification = sbn.notification ?: return false

        // Ignore summary group notifications to avoid double-processing grouped notifications
        if ((notification.flags and Notification.FLAG_GROUP_SUMMARY) != 0) {
            return false
        }

        val extras = notification.extras ?: return false

        val title = extras.getCharSequence(Notification.EXTRA_TITLE)?.toString()?.trim() ?: ""
        val text = extras.getCharSequence(Notification.EXTRA_TEXT)?.toString()?.trim() ?: ""
        val bigText = extras.getCharSequence(Notification.EXTRA_BIG_TEXT)?.toString()?.trim() ?: ""

        val effectiveBody = if (bigText.isNotBlank()) bigText else text

        Log.d(TAG, "Inspecting notification: pkg=$packageName, title='$title', body='$effectiveBody'")

        // Check if this notification could be from Yape or contains payment info
        if (!YapeNotificationParser.isPotentialPaymentNotification(packageName, title, effectiveBody)) {
            return false
        }

        // Parse notification
        val parsed = YapeNotificationParser.parse(packageName, title, effectiveBody)
        if (parsed != null && parsed.amount > 0.0) {
            val fingerprint = "${parsed.sender.trim().lowercase()}_${String.format(Locale.US, "%.2f", parsed.amount)}"
            val now = System.currentTimeMillis()

            // For real-time notifications, check recent memory cache deduplication
            if (!isCatchUp) {
                processedPayments.entries.removeIf { now - it.value > DEDUPLICATION_WINDOW_MS * 2 }
                val lastTime = processedPayments[fingerprint]
                if (lastTime != null && (now - lastTime) < DEDUPLICATION_WINDOW_MS) {
                    Log.d(TAG, "Skipping duplicate notification for $fingerprint")
                    return false
                }
                processedPayments[fingerprint] = now
            }

            Log.i(TAG, "Detected Yape Payment! Sender: ${parsed.sender}, Amount: S/ ${parsed.amount}")

            val payment = YapePayment(
                sender = parsed.sender,
                amount = parsed.amount,
                currency = parsed.currency,
                timestamp = if (sbn.postTime > 0) sbn.postTime else now,
                rawTitle = parsed.rawTitle,
                rawBody = parsed.rawBody,
                packageName = parsed.packageName
            )

            scope.launch {
                try {
                    val repo = YapeMonitorApp.instance.repository
                    // Check if already in database (especially important for active/historical notifications)
                    if (!repo.isPaymentAlreadySaved(payment)) {
                        repo.processIncomingPayment(payment, isCatchUp = isCatchUp)
                    } else {
                        Log.d(TAG, "Payment already saved in database: ${parsed.sender} - ${parsed.amount}")
                    }
                } catch (e: Exception) {
                    Log.e(TAG, "Error saving incoming payment", e)
                }
            }
            return true
        }
        return false
    }
}
